// --- Write all files ---
function ensureDir(dir: string) {
  if (!fs.existsSync(dir)) {
    fs.mkdirSync(dir, { recursive: true });
  }
}

function main() {
  ensureDir(outputDir);

  const files: Record<string, string> = {
    'colorScales.js': generateColorScales(),
    'paletteDark.js': generatePaletteDark(),
    'shadows.js': generateShadows(),
    'shape.js': generateShape(),
    'size.js': generateSize(),
    'typography.js': generateTypography(),
    'spacing.js': generateSpacing(),
    'extensions.js': generateExtensions(),
    'themedVariables.js': generateThemedVariables(),
  };

  for (const [filename, content] of Object.entries(files)) {
    const filePath = path.join(outputDir, filename);
    fs.writeFileSync(filePath, content, 'utf-8');
    console.log(`  ✓ ${filename}`);
  }

  console.log(`\nGenerated ${Object.keys(files).length} files in ${outputDir}`);
}

main();
