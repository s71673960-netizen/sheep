// --- Generate shadows.js ---
function generateShadows() {
  const { shadows: s } = tokens;

  // Map 4 design-token levels to MUI's 25-element array:
  // 0: none, 1-4: small, 5-8: medium, 9-12: large, 13-24: xlarge
  const shadowArray: string[] = [
    'none',
    ...Array(4).fill(s.small),
    ...Array(4).fill(s.medium),
    ...Array(4).fill(s.large),
    ...Array(12).fill(s.xlarge),
  ];

  const lines: string[] = [];
  lines.push('// Auto-generated by generateThemeTokens.ts - DO NOT EDIT');
  lines.push('');
  lines.push(`const shadows = ${JSON.stringify(shadowArray, null, 2)};`);
  lines.push('');
  lines.push('export default shadows;');
  lines.push('');
  return lines.join('\n');
}

