import * as fs from 'node:fs';
import * as path from 'node:path';

const tokensPath = path.resolve(__dirname, 'design-tokens.json');
const outputDir = path.resolve(__dirname, 'generated');

const tokens = JSON.parse(fs.readFileSync(tokensPath, 'utf-8'));

function resolveReference(ref: string): string {
  if (ref.startsWith('#')) return ref;

  const parts = ref.split('/');
  const [root, ...rest] = parts;

  if (root === 'lightMode' || root === 'darkMode') {
    const [color, shade] = rest;
    return tokens.colors[root]?.[color]?.[shade] ?? ref;
  }
  if (root === 'neutral') {
    return tokens.colors.neutral[rest[0]] ?? ref;
  }
  if (root === 'overlay') {
    const [color, shade] = rest;
    return tokens.colors.overlay?.[color]?.[shade] ?? ref;
  }
  return ref;
}

function resolveThemedVariables(themeMode: 'light' | 'dark') {
  const vars = tokens.colors.themedVariables[themeMode];
  const resolved: Record<string, Record<string, string>> = {};
  for (const category of Object.keys(vars)) {
    resolved[category] = {};
    for (const [key, value] of Object.entries(vars[category])) {
      resolved[category][key] = resolveReference(value as string);
    }
  }
  return resolved;
}

// --- Generate colorScales.js ---
function generateColorScales() {
  const { lightMode, darkMode } = tokens.colors;

  const lines: string[] = [];
  lines.push('// Auto-generated by generateThemeTokens.ts - DO NOT EDIT');
  lines.push('');

  for (const [name, scale] of Object.entries(lightMode)) {
    lines.push(`export const ${name} = ${JSON.stringify(scale, null, 2)};`);
    lines.push('');
  }

  lines.push('// Dark mode scales');
  for (const [name, scale] of Object.entries(darkMode)) {
    lines.push(`export const dark_${name} = ${JSON.stringify(scale, null, 2)};`);
    lines.push('');
  }

  return lines.join('\n');
}

